# Builds js/icons.js from Phosphor Icons (MIT).
# Usage: python3 tools/buildicons.py <node_modules dir>
import re, sys, json, os
nm = sys.argv[1]
PH = os.path.join(nm, '@phosphor-icons/core/assets')
CTRL = {  # duotone: car controls and pictures
  'car': 'car-profile', 'window': 'arrow-square-down', 'key': 'key', 'signalLeft': 'arrow-fat-left', 'signalRight': 'arrow-fat-right',
  'brake': 'octagon', 'horn': 'megaphone', 'parkingBrake': 'letter-circle-p', 'flashers': 'warning', 'headlights': 'headlights',
  'wipers': 'cloud-rain', 'defroster': 'wind', 'auto': 'lightning-a', 'engineOff': 'power', 'engine': 'engine', 'seatbelt': 'seatbelt',
  'talk': 'chat-circle-dots', 'flag': 'flag-checkered', 'exam': 'exam', 'turnLeft': 'arrow-bend-up-left', 'laneLeft': 'path',
  'parkSpace': 'letter-circle-p', 'look': 'eye', 'steer': 'steering-wheel', 'road': 'road-horizon',
}
UI = {  # bold: interface glyphs
  'speaker': 'speaker-high', 'mic': 'microphone', 'close': 'x', 'back': 'caret-left', 'info': 'info', 'gear': 'gear-six',
  'home': 'house-simple', 'practice': 'target', 'profile': 'user-circle', 'book': 'book-open-text', 'bolt': 'lightning',
  'check': 'check', 'x': 'x', 'lock': 'lock-simple', 'flame': 'fire', 'search': 'magnifying-glass', 'globe': 'globe-simple',
  'chevron': 'caret-right', 'repeat': 'repeat', 'eye': 'eye', 'steer': 'steering-wheel', 'arrowL': 'arrow-fat-left', 'arrowR': 'arrow-fat-right',
  'power': 'power', 'turnL': 'arrow-bend-up-left', 'turnR': 'arrow-bend-up-right', 'car': 'car-profile', 'flag': 'flag-checkered',
}
FILL = {'arrowL': 'arrow-fat-left', 'arrowR': 'arrow-fat-right'}
def inner(path):
    s = open(path).read()
    return re.sub(r'^<svg[^>]*>|</svg>\s*$', '', s.strip())
out = {'ctrl': {}, 'ui': {}, 'fill': {}}
for k, n in CTRL.items(): out['ctrl'][k] = inner(f'{PH}/duotone/{n}-duotone.svg')
for k, n in UI.items(): out['ui'][k] = inner(f'{PH}/bold/{n}-bold.svg')
for k, n in FILL.items(): out['fill'][k] = inner(f'{PH}/fill/{n}-fill.svg')
js = '// Generated by tools/buildicons.py from Phosphor Icons (MIT, phosphoricons.com). Do not edit by hand.\n'
js += 'export const CTRL = ' + json.dumps(out['ctrl']) + ';\n'
js += 'export const UIB = ' + json.dumps(out['ui']) + ';\n'
js += 'export const FILLED = ' + json.dumps(out['fill']) + ';\n'
open(os.path.join(os.path.dirname(__file__), '..', 'js', 'icons.js'), 'w').write(js)
print('ok', len(js))
